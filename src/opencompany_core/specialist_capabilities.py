def derive_specialist_capabilities(department: str, title: str) -> tuple[str, ...]:
    """Return up to four curated domain methods relevant to a specialist title."""
    rules = _RULES.get(department)
    defaults = _DEFAULTS.get(department)
    if rules is None or defaults is None:
        raise ValueError(f"unknown specialist department: {department}")
    lowered = title.casefold()
    matched = sorted(
        ((len(keyword), capability) for keyword, capability in rules.items() if keyword in lowered),
        reverse=True,
    )
    capabilities: list[str] = []
    for _, capability in matched:
        if capability not in capabilities:
            capabilities.append(capability)
        if len(capabilities) >= 4:
            break
    for capability in defaults:
        if len(capabilities) >= 2:
            break
        if capability not in capabilities:
            capabilities.append(capability)
    return tuple(capabilities[:4])
